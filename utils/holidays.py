def get_active_holiday(today: date | None = None) -> dict | None:
    """Праздник, действующий сегодня (сравнение по ММ-ДД, год не важен),
    либо None, если сегодня обычный день."""
    today = today or date.today()
    key = today.strftime("%m-%d")
    for holiday in HOLIDAYS:
        if holiday["date"] == key:
            return holiday
    return None


def _bonus_word(holiday: dict) -> str:
    return plural_credits(holiday.get("bonus_credits", 0))


def format_broadcast_text(holiday: dict) -> str:
    """Текст поздравления для рассылки всем пользователям с профилем."""
    bonus = holiday.get("bonus_credits", 0)
    return holiday["text"].format(bonus=bonus, bonus_word=_bonus_word(holiday))


def format_bonus_line(holiday: dict) -> str:
    """Короткая строка про праздничный бонус — добавляется в уведомление
    об одобренном инсайде."""
    bonus = holiday.get("bonus_credits", 0)
    return f"🎉 Праздничный бонус: +{bonus} {_bonus_word(holiday)} доверия!"
